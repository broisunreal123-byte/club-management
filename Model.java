package model;

/**
 *
 * @author ADMIN
 */
public abstract class Model {
    private String status;


    public Model() {
    }

    public Model(String status) {
        this.status = status;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public abstract void display();

    public abstract String toFileString();
}
